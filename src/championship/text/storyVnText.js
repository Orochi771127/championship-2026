/** A line of copy with {params} filled; unknown locales read Traditional Chinese, unknown keys return null. */
export function storyVnText(key, locale = "zh-Hant", params = {}) {
  const table = STORY_VN_COPY[locale] ?? STORY_VN_COPY["zh-Hant"];
  const raw = table[key] ?? STORY_VN_COPY["zh-Hant"][key];
  if (typeof raw !== "string") return null;
  return raw.replace(/\{(\w+)\}/g, (match, name) => (params[name] !== undefined && params[name] !== null ? String(params[name]) : match));
}
