export function cyberDungeonText(key, values = {}, locale = getLocale()) {
  const lang = Object.hasOwn(CYBER_DUNGEON_COPY, locale) ? locale : 'zh-Hant';
  const raw = CYBER_DUNGEON_COPY[lang][key] ?? CYBER_DUNGEON_COPY['zh-Hant'][key] ?? '';
  return raw.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}
