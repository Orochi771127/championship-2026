export const DATA_ARENA_TEXT = Object.freeze({ "zh-Hant": Object.freeze(ZH), en: Object.freeze(EN) });

export function arenaText(key, params = null) {
  const locale = getLocale();
  const table = locale === "zh-Hant" ? ZH : EN;
  let text = table[key] ?? ZH[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
