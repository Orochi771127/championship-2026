export const JUICY_SHOWCASE_TEXT = TABLES;

/** The current locale's copy for `key`, with {name} placeholders filled. */
export function juicyText(key, params = null, locale = getLocale()) {
  const table = TABLES[locale] ?? TABLES["zh-Hant"];
  const template = table[key] ?? TABLES["zh-Hant"][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
