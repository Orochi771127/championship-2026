const PLACEHOLDER = /\{(tamer|partner|n|total|done)\}/g;

/** One string, with {tamer}/{partner}/{n}... filled; zh-Hant when the locale lacks it; null when unknown. */
export function dataAreaText(key, locale = "zh-Hant", params = {}) {
  const table = DATA_AREA_STORY_COPY[locale] ?? DATA_AREA_STORY_COPY["zh-Hant"];
  const raw = table[key] ?? DATA_AREA_STORY_COPY["zh-Hant"][key];
  if (typeof raw !== "string") return null;
  return raw.replace(PLACEHOLDER, (match, name) => (params[name] === undefined || params[name] === null ? match : String(params[name])));
}

