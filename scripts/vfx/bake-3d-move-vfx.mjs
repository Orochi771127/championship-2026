// 00GameDevs Three.js effect library (MIT). Like pixelfx, the
// library is a local authoring tool, never a game dependency: this script
// renders each effect once in a headless browser (three 0.187, transparent
// background), box-averages the render to texels, finishes them with the same
// stepped light as the pixelfx pieces (pixelfxBakeLib.finish, no outline) and
// encodes them with the same encoder (encodePieceLook), so the game plays and
// recolours them exactly like every other baked piece. The pieces ship in
// small group modules the game loads only when a fighter on the field owns a
// move that plays one.
//
// Spec (scripts/vfx/move-piece-3d-specs.mjs): fx, the library effect id; o, its
// options; cam {el, az, d, ly, fov}; hit, the second a continuous effect is
// hit; stop, the second it is told to wind down; beam [from x, to x], a beam's span; from/until, the seconds kept; tex, texels across the 384 px render (128);
// fps, frames kept per second (20); bloom, the brightness the light layer starts at (0.7);
// anchor/fit/noSmoke/loop as in bake-move-piece-vfx.mjs; group, the module; base, the shared
// piece it replaces (played until the group is loaded).
//
// Usage: node scripts/vfx/bake-3d-move-vfx.mjs [--check] [--only a,b] [--sheet <dir>]
//   GAMEDEVS_HOME  a folder holding the downloaded effects (effects/<id>.js, hash-checked
//                  against catalog.v2.json), three@0.187.0 (node_modules) and harness.html
