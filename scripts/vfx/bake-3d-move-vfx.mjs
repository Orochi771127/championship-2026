function serve(home) {
  const types = {'.js': 'text/javascript', '.html': 'text/html', '.json': 'application/json'};
  const server = http.createServer((q, r) => {
    const p = path.join(home, decodeURIComponent(q.url.split('?')[0]));
    if (!p.startsWith(home) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { r.writeHead(404); r.end(); return; }
    r.writeHead(200, {'content-type': types[path.extname(p)] ?? 'application/octet-stream'});
    fs.createReadStream(p).pipe(r);
  });
  return new Promise(ok => server.listen(0, '127.0.0.1', () => ok(server)));
}

function verifyHome(home) {
  const catalog = JSON.parse(fs.readFileSync(path.join(home, 'catalog.v2.json'), 'utf8'));
  const byId = new Map(catalog.assets.filter(a => a.kind === 'effect').map(a => [a.id, a]));
  return id => {
    const entry = byId.get(id), file = path.join(home, 'effects', `${id}.js`);
    if (!entry || !fs.existsSync(file)) throw new Error(`${id}: not in GAMEDEVS_HOME`);
    const sha = createHash('sha256').update(fs.readFileSync(file)).digest('hex');
    if (sha !== entry.download.sha256) throw new Error(`${id}: sha256 differs from the catalog`);
  };
}

const unb64 = s => Uint8Array.from(Buffer.from(s, 'base64'));
// a soft light layer: two 3 x 3 box passes over the bloom proxy
function soften(L, w, h) {
  let a = L;
  for (let pass = 0; pass < 2; pass++) {
    const b = new Float32Array(w * h);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      let s = 0, n = 0;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) { const X = x + dx, Y = y + dy; if (X >= 0 && Y >= 0 && X < w && Y < h) { s += a[Y * w + X]; n++; } }
      b[y * w + x] = s / n;
    }
    a = b;
  }
  return a;
}

async function bakePiece(page, port, name, spec) {
  const tex = spec.tex ?? 128, cam = spec.cam ?? {};
  const q = new URLSearchParams({id: spec.fx, alpha: spec.opaque ? '0' : '1', px: String(PX), o: JSON.stringify(spec.o ?? {}),
    ...(spec.hit !== undefined ? {hit: String(spec.hit)} : {}), ...(spec.stop !== undefined ? {stop: String(spec.stop)} : {}),
    ...(spec.beam ? {bx: String(spec.beam[0]), ex: String(spec.beam[1])} : {}), ...Object.fromEntries(Object.entries(cam).map(([k, v]) => [k, String(v)]))});
  await page.goto(`http://127.0.0.1:${port}/harness.html?${q}`);
  await page.waitForFunction('window.__ready', null, {timeout: 120000});
  const [px, py] = await page.evaluate(() => window.__origin());
  const from = Math.round((spec.from ?? 0) * FPS), until = Math.max(from + 1, Math.round((spec.until ?? 1.2) * FPS));
  // the render runs at 30 fps; the piece keeps `fps` of them (20 by default: half the bytes, same motion)
  const fps = spec.fps ?? 20;
  const frames = [], lights = [];
  for (let i = 0, last = -1; i < until; i++) {
    await page.evaluate(dt => window.__step(dt), 1 / FPS);
    if (i < from) continue;
    const slot = Math.floor((i - from) * fps / FPS);
    if (slot === last) continue;
    last = slot;
    const {rgba, light} = await page.evaluate(([t, thr]) => window.__texels(t, thr), [tex, spec.bloom ?? 0.7]);
    const c = unb64(rgba), l = unb64(light), n = tex * tex;
    const raw = new Uint32Array(n), lit = new Uint32Array(n), L = new Float32Array(n);
    for (let j = 0; j < n; j++) {
      let a = c[j * 4 + 3];
      // an opaque render (an effect that composites its own glow) keys its alpha off brightness
      if (spec.opaque) a = Math.min(255, Math.max(c[j * 4], c[j * 4 + 1], c[j * 4 + 2]) * 2);
      raw[j] = (c[j * 4] | (c[j * 4 + 1] << 8) | (c[j * 4 + 2] << 16) | (a << 24)) >>> 0;
      lit[j] = (l[j * 3] | (l[j * 3 + 1] << 8) | (l[j * 3 + 2] << 16)) >>> 0;
      L[j] = Math.max(l[j * 3], l[j * 3 + 1], l[j * 3 + 2]) / 255;
    }
    frames.push(finish({raw, light: lit}, tex, tex, () => false, {noSmoke: spec.noSmoke, outline: false}));
    lights.push(spec.noGlow ? null : soften(L, tex, tex));
  }
  const count = d => { let n = 0; for (let j = 3; j < d.length; j += 4) if (d[j]) n++; return n; };
  const peak = Math.max(...frames.map(count));
  // the wind-up (almost nothing lit) and the empty tail go, frames and light together
  if (!spec.loop) {
    while (frames.length > 1 && count(frames[0]) < peak * 0.04) { frames.shift(); lights.shift(); }
    while (frames.length > 1 && count(frames[frames.length - 1]) === 0) { frames.pop(); lights.pop(); }
  }
  const k = tex / PX;
  return encodePieceLook(name, spec, {frames, lights: spec.noGlow ? [] : lights, w: tex, h: tex, OX: Math.round(px * k), OY: Math.round(py * k),
    margin: 0, fps, peak, count, source: `00gamedevs/${spec.fx}`});
}

function indexText(groups) {
  const names = Object.fromEntries(Object.entries(groups).flatMap(([group, looks]) => looks.map(l => [l.name, group])));
  const fallback = Object.fromEntries(Object.values(groups).flat().map(l => [l.name, l.base ?? null]));
  const table = o => `{\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')}\n}`;
  return `// Which group module holds each three.js move piece (UNIFIED_MOVES_20261118). GENERATED by
// scripts/vfx/bake-3d-move-vfx.mjs; edit the bake, not this file. The game loads a
// group only when a fighter on the field owns a move that plays one of its pieces.
export const MOVE_VFX_3D_PIECE_GROUP = Object.freeze(${table(names)});
// the shared piece each one replaces, played while its group is still loading
export const MOVE_VFX_3D_FALLBACK = Object.freeze(${table(fallback)});
export const MOVE_VFX_3D_PIECE_GROUPS = Object.freeze({
${Object.keys(groups).sort().map(g => `  ${JSON.stringify(g)}: () => import('./moveVfxPieceSprites3d.${g}.js')`).join(',\n')}
});
`;
}

async function writeSheet(dir, looks) {
  const {chromium} = await import('playwright');
  fs.mkdirSync(dir, {recursive: true});
  // one strip per look: ten frames, colour over a field green, light added in a warm white
  const html = `<canvas id=c></canvas><script>const L=${JSON.stringify(looks.map(l => ({name: l.name, w: l.w, h: l.h, gw: l.gw, gh: l.gh, palette: l.palette, frames: l.frames, glow: l.glow})))};
const K=${JSON.stringify((await import('./pixelfxBakeLib.mjs')).KEYS)},Z=2,cell=300,pad=6,cols=10,c=document.getElementById('c');c.width=cols*(cell+pad);c.height=L.length*(cell+pad);
const x=c.getContext('2d');x.fillStyle='#466e34';x.fillRect(0,0,c.width,c.height);
const rows=(s,w,h,f)=>{s.split('/').forEach((r,y)=>{let X=0;for(const[,k,n]of r.matchAll(/([^0-9])(\\d*)/g)){const m=n?+n:1;if(k!=='.')for(let q=0;q<m;q++)f(X+q,y,k);X+=m;}});};
L.forEach((l,li)=>{const n=l.frames.length,m=Math.min(cols,n);for(let ci=0;ci<m;ci++){const fi=Math.floor(ci*n/m),s=Math.min(Z,cell/Math.max(l.w,l.h));
const ox=ci*(cell+pad),oy=li*(cell+pad);rows(l.frames[fi],l.w,l.h,(X,Y,k)=>{const p=l.palette[K.indexOf(k)];x.fillStyle='rgba('+p[0]+','+p[1]+','+p[2]+','+p[3]+')';x.fillRect(ox+X*s,oy+Y*s,s,s);});
x.globalCompositeOperation='lighter';if(l.glow[fi])rows(l.glow[fi],l.gw,l.gh,(X,Y,k)=>{const v=('abcdefgh'.indexOf(k)+.5)/8*.8;x.fillStyle='rgba(255,225,170,'+v+')';x.fillRect(ox+X*2*s,oy+Y*2*s,2*s,2*s);});x.globalCompositeOperation='source-over';}});</script>`;
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(html);
  await page.locator('#c').screenshot({path: path.join(dir, 'move-piece-3d-sheet.png')});
  await browser.close();
}

const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1].split(',') : null;
if (args.includes('--check')) {
  const index = await import(pathToFileURL(path.join(root, INDEX)).href);
  const missing = Object.keys(MOVE_PIECE_3D).filter(n => !index.MOVE_VFX_3D_PIECE_GROUP[n]);
  if (missing.length) { console.error('missing 3d pieces:', missing.join(', ')); process.exit(1); }
  for (const g of Object.keys(index.MOVE_VFX_3D_PIECE_GROUPS)) {
    const mod = await index.MOVE_VFX_3D_PIECE_GROUPS[g]();
    for (const [n, gg] of Object.entries(index.MOVE_VFX_3D_PIECE_GROUP)) if (gg === g && !mod.MOVE_VFX_PIECE_SPRITES[n]) { console.error(`${n} not in group ${g}`); process.exit(1); }
  }
  console.log(JSON.stringify({pieces: Object.keys(index.MOVE_VFX_3D_PIECE_GROUP).length, groups: Object.keys(index.MOVE_VFX_3D_PIECE_GROUPS).length}));
} else {
  const home = process.env.GAMEDEVS_HOME && path.resolve(process.env.GAMEDEVS_HOME);
  if (!home || !fs.existsSync(path.join(home, 'harness.html'))) { console.error('set GAMEDEVS_HOME to the 00GameDevs effect folder'); process.exit(1); }
  const check = verifyHome(home);
  const server = await serve(home), port = server.address().port;
  const {chromium} = await import('playwright');
  const browser = await chromium.launch({args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport: {width: PX, height: PX}});
  const looks = [], failed = [];
  try {
    for (const [name, spec] of Object.entries(MOVE_PIECE_3D)) {
      if (only && !only.includes(name)) continue;
      check(spec.fx);
      let look;
      try { look = await bakePiece(page, port, name, spec); } catch (error) { failed.push(name); console.error(`${name}: ${error.message}`); continue; }
      look.group = spec.group; look.base = spec.base ?? null;
      looks.push(look);
      console.log(`${name.padEnd(22)} ${String(look.frames.length).padStart(3)} frames ${look.w}x${look.h} ${look.palette.length} keys ${Math.round(JSON.stringify(look.frames).length / 1024)} KB`);
    }
  } finally { await browser.close(); server.close(); }
  if (failed.length) { console.error(`failed: ${failed.join(', ')}`); process.exitCode = 1; }
  if (!only && !failed.length) {
    const groups = {};
    for (const look of looks) (groups[look.group] ??= []).push(look);
    for (const file of fs.readdirSync(path.join(root, DIR)).filter(f => /^moveVfxPieceSprites3d\.[^.]+\.js$/.test(f))) fs.unlinkSync(path.join(root, DIR, file));
    for (const [group, list] of Object.entries(groups)) {
      const text = moduleText(list, {header: NOTICE_3D});
      fs.writeFileSync(path.join(root, groupFile(group)), text);
      console.log(`${groupFile(group)}: ${Buffer.byteLength(text)} bytes`);
    }
    fs.writeFileSync(path.join(root, INDEX), indexText(groups));
  }
  const sheet = args.indexOf('--sheet');
  if (sheet >= 0) await writeSheet(path.resolve(args[sheet + 1]), looks);
}
