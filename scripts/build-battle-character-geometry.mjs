// Only numeric transforms and hashes are promoted from the previous pixel-equality
// audit. Existing production images are read and hashed; never copied or edited.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const digest=path=>createHash('sha256').update(fs.readFileSync(path)).digest('hex');
const evidence=read('docs/art/production/tooling-pilot-r1/scale-review/character-native-scale-candidates.json');
const base='assets/production/internal-faithful-baseline/characters-v1/';
const manifest=read(base+'manifest.json');
const entities={};
const profiles={};
const speedReceipt=read('docs/research/BATTLE_ACTION_NATIVES_CPU_2026-09-07.json');
assert.equal(speedReceipt.speciesSpeeds.length,228);
const speeds=speedReceipt.speciesSpeeds.map((s,i)=>{
  assert.equal(s.speciesId,i);
  assert.ok(Number.isSafeInteger(s.walkQ12)&&Number.isSafeInteger(s.runQ12));
  return {walkQ12:s.walkQ12,runQ12:s.runQ12};
});
assert.equal(manifest.records.length,224);
assert.equal(manifest.speciesBindings.length,228);
for(const {entityId} of manifest.records){
  const witness=evidence.entities.find(e=>e.entityId===entityId);
  const record=manifest.records.find(e=>e.entityId===entityId);
  const runtime=read(base+record.runtime);
  const files=Object.entries(witness.sourceHashes).filter(([name])=>name.replaceAll('\\','/').startsWith(base));
  for(const [name,hash] of files){
    assert.equal(digest(name),hash);
    assert.equal(record.files.find(f=>base+f.path===name.replaceAll('\\','/'))?.sha256.toLowerCase(),hash);
  }
  const frames={};
  for(const frame of witness.frames.filter(f=>f.side==='main')){
    assert.equal(frame.sourceOamAffineCount,0);
    if(!frame.isBlank)assert.equal(frame.scaleStatus,'RAW_TRANSFER_DECODE_PIXEL_EQUALITY_VERIFIED');
    frames[frame.texture]={blank:frame.isBlank,scale:frame.packedPixelsPerNativePixel,
      origin:frame.packedSourceOrigin,sourceSize:[frame.packedSourceSize.w,frame.packedSourceSize.h],
      nativeBounds:frame.nativeAlphaBounds};
  }
  for(const animation of runtime.sides.main.animations){
    for(const frame of animation.frames)assert.ok(frames[frame.texture]);
  }
  entities[entityId]={files:files.map(([name,hash])=>[name.replaceAll('\\','/').slice(base.length),hash]),frames};
  // Runtime action timing is numeric metadata. Preserve raw sequence ids and
  // source tick counts; the archive's provisional semantic aliases are unused.
  profiles[entityId]={sequences:runtime.sides.main.animations.map(animation=>{
    assert.ok([1,2].includes(animation.playbackMode));
    assert.ok(animation.frames.every(frame=>Number.isSafeInteger(frame.ticks)&&frame.ticks>0));
    return {id:animation.id,playbackMode:animation.playbackMode,loopStartFrame:animation.loopStartFrame??0,
      frames:animation.frames.map(({cell,ticks})=>({cell,ticks}))};
  }),cells:Object.fromEntries(witness.frames.filter(f=>f.side==='main').map(f=>[f.cell,f.nativeCellBounds]))};
}
const target='src/data/championship/battleCharacterGeometry.js';
const output='// Generated by build-battle-character-geometry.mjs; numeric geometry, no pixels.\n'
  +'export const BATTLE_CHARACTER_GEOMETRY = '+JSON.stringify(entities)+';\n';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output);else fs.writeFileSync(target,output);
const profileTarget='src/data/championship/battleCharacterProfiles.js';
const profileOutput='// Generated by build-battle-character-geometry.mjs; numeric Main animation metadata.\n'
  +'export const BATTLE_CHARACTER_PROFILES = '+JSON.stringify(profiles)+';\n'
  +'export const BATTLE_SPECIES_ENTITIES = '+JSON.stringify(manifest.speciesBindings.map(b=>b.entityId))+';\n'
  +'// Original CPU helpers 02114320 / 0211436C, species table 020C1374 + id*84.\n'
  +'export const BATTLE_SPECIES_MOVEMENT = '+JSON.stringify(speeds)+';\n';
for(let i=0;i<manifest.speciesBindings.length;i++)assert.equal(manifest.speciesBindings[i].speciesId,`species-${String(i).padStart(3,'0')}`);
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(profileTarget,'utf8'),profileOutput);else fs.writeFileSync(profileTarget,profileOutput);
console.log('Battle geometry: '+Object.values(entities).reduce((n,e)=>n+Object.keys(e.frames).length,0)+' Main cells checked');
