// Geometry only. The offline evidence audit owns raw decoding; no research asset
// or research path is fetched by the runtime.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => JSON.parse(fs.readFileSync(path.join(root, name), "utf8"));
const base = "assets/production/internal-faithful-baseline/characters-v1/";
const evidence = read("docs/art/production/tooling-pilot-r1/scale-review/character-main-zero-scale-candidates.json");
const manifest = read(base + "manifest.json");
const output = {};
for (const record of manifest.records) {
  const candidate = evidence.records.find((item) => item.entityId === record.entityId);
  const main = candidate?.sides.main;
  assert.equal(main?.verifiedPixelMatch, true, record.entityId);
  const files = [
    [record.runtime, candidate.baselineRuntimeSha256],
    [`${record.entityId}/main-atlas-00.json`, main.atlasJsonSha256],
    [`${record.entityId}/main-atlas-00.png`, main.atlasPngSha256]
  ];
  for (const [name, hash] of files) {
    assert.equal(createHash("sha256").update(fs.readFileSync(path.join(root, base, name))).digest("hex"), hash);
    assert.equal(record.files.find((file) => file.path === name)?.sha256.toLowerCase(), hash);
  }
  const runtime = read(base + record.runtime);
  assert.equal(runtime.sides.main.animations.find((item) => item.id === 0).frames[0].texture, main.texture);
  const scale = main.packedPixelsPerNativePixel;
  assert.equal(main.packedTrim.w / scale, main.nativeVisibleSize[0]);
  assert.equal(main.packedTrim.h / scale, main.nativeVisibleSize[1]);
  output[record.entityId] = { packedPixelsPerNativePixel: scale, texture: main.texture, files };
}
assert.equal(Object.keys(output).length, 224);
const target = path.join(root, "src/data/championship/characterNativeSizing.js");
const content = "// Generated by scripts/build-character-native-sizing.mjs. Main action 0 first frame only.\n"
  + "// Packed enlargement is per cell, not artProfile.scale. Other poses require separate metadata.\n"
  + `export const CHARACTER_NATIVE_SIZING = ${JSON.stringify(output, null, 2)};\n`;
if (process.argv.includes("--check")) assert.equal(fs.readFileSync(target, "utf8"), content);
else fs.writeFileSync(target, content);
console.log("CHARACTER_NATIVE_SIZING: 224 static Main frames, hashes and dimensions PASS");
