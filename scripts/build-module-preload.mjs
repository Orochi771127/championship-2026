// Write the startup modulepreload list into championship.html.
//
// The game ships unbundled ES modules, so the browser cannot discover a module
// until it has parsed the one that imports it. Measured from a real Chrome load,
// that is fourteen sequential waves: on localhost the gaps are milliseconds, but
// every wave is a round trip, so on a phone they are the load.
//
// Naming each startup module up front lets the browser fetch them in parallel
// instead of discovering them a wave at a time. Nothing about the module graph
// changes; only when the requests start.
//
// Run with --check to verify the block matches the graph without writing.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = "src/championship/app/main.js";
const PAGE = "championship.html";
const BEGIN = "    <!-- modulepreload: generated by scripts/build-module-preload.mjs -->";
const END = "    <!-- /modulepreload -->";

const STATIC_IMPORT = /^\s*(?:import|export)(?:[^'"]*?from)?\s*['"]([^'"]+)['"]/gm;

function resolveSpecifier(fromFile, specifier) {
  if (!specifier.startsWith(".")) return null;
  const resolved = path.resolve(path.dirname(fromFile), specifier);
  return fs.existsSync(resolved) ? resolved : null;
}

/** Every module the entry reaches through static imports, in discovery order. */
function startupGraph() {
  const seen = new Set();
  const order = [];
  const queue = [path.join(root, ENTRY)];
  while (queue.length) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    order.push(file);
    let text;
    try { text = fs.readFileSync(file, "utf8"); } catch { continue; }
    for (const match of text.matchAll(STATIC_IMPORT)) {
      const next = resolveSpecifier(file, match[1]);
      if (next && !seen.has(next)) queue.push(next);
    }
  }
  // The entry itself already has its own script tag.
  return order.slice(1).map((file) => path.relative(root, file).split(path.sep).join("/"));
}

function block(modules) {
  const links = modules.map((href) => {
    const as = href.endsWith(".json") ? ' as="fetch" crossorigin' : "";
    return `    <link rel="modulepreload" href="./${href}"${as}>`;
  });
  return [BEGIN, ...links, END].join("\n");
}

const modules = startupGraph();
const pagePath = path.join(root, PAGE);
const page = fs.readFileSync(pagePath, "utf8");
const next = block(modules);
const begin = page.indexOf(BEGIN);
const updated = begin === -1
  ? page.replace("</head>", `${next}\n  </head>`)
  : page.slice(0, begin) + next + page.slice(page.indexOf(END) + END.length);

if (process.argv.includes("--check")) {
  if (updated !== page) {
    console.error(`MODULE_PRELOAD_STALE: ${modules.length} startup modules; run scripts/build-module-preload.mjs`);
    process.exit(1);
  }
  console.log(`module preload check ok: ${modules.length} startup modules`);
} else {
  fs.writeFileSync(pagePath, updated);
  console.log(`Wrote ${modules.length} modulepreload links into ${PAGE}.`);
}
