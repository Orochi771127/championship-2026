"""Grass tiles for hunt ground contact (2026-11-25).

python scripts/build-hunt-grass-tiles-20261125.py
Reads each grass map's day image (1 px = 1 world px, 180x180 tiles of 16 px) and marks
a tile as grass when its mean colour is green-dominant; dirt paths, water, plateaus and
props are left out. Writes src/championship/presentation/vs2/huntThree/grassTiles.mjs
(base64 bitsets, row-major, bit (y*180+x) little-endian within each byte).
"""
import base64
from pathlib import Path
import numpy as np
from PIL import Image

SRC = {
    'hm01': 'assets/production/hunt/hm01-three-r1-20261022/field_hm01_01-frame-00-rgb-050917d71fe9.webp',
    'hm02': 'assets/production/hunt/three-fallback-20261023/hm02-day.webp',
    'hm03': 'assets/production/hunt/three-fallback-20261023/hm03-day.webp',
    'hm04': 'assets/production/hunt/three-fallback-20261023/hm04-day.webp',
}
rows = []
for key, path in SRC.items():
    a = np.asarray(Image.open(path).convert('RGB'), dtype=np.float32)
    assert a.shape == (2880, 2880, 3), (key, a.shape)
    t = a.reshape(180, 16, 180, 16, 3).mean(axis=(1, 3))
    r, g, b = t[..., 0], t[..., 1], t[..., 2]
    # Savanna grass is yellow-green, so it gets its own threshold.
    grass = ((g >= r * 0.98) & (g > b * 1.25) & (g > 90)) if key == 'hm02' else ((g > r * 1.06) & (g > b * 1.12) & (g > 60))
    bits = np.packbits(grass.reshape(-1).astype(np.uint8), bitorder='little')
    rows.append(f"  {key}: '{base64.b64encode(bits.tobytes()).decode()}'")
    print(key, int(grass.sum()))
Path('src/championship/presentation/vs2/huntThree/grassTiles.mjs').write_text(
    '// Generated by scripts/build-hunt-grass-tiles-20261125.py: which open tiles of the grass\n'
    '// maps are grass (not dirt paths, water, plateaus or props), for ground contact tufts.\n'
    'export const HUNT_GRASS_TILE_BITS = Object.freeze({\n' + ',\n'.join(rows) + '\n});\n\n'
    'const decoded = new Map();\n'
    '/** True when tile (x, y) of the map is grass; false off the map or for maps without data. */\n'
    'export function huntGrassTile(mapKey, x, y) {\n'
    '  const data = HUNT_GRASS_TILE_BITS[mapKey];\n'
    '  if (!data || !Number.isInteger(x) || !Number.isInteger(y) || x < 0 || y < 0 || x >= 180 || y >= 180) return false;\n'
    '  let bytes = decoded.get(mapKey);\n'
    "  if (!bytes) { bytes = Uint8Array.from(atob(data), c => c.charCodeAt(0)); decoded.set(mapKey, bytes); }\n"
    '  const i = y * 180 + x;\n'
    '  return ((bytes[i >> 3] >> (i & 7)) & 1) === 1;\n'
    '}\n', encoding='utf-8', newline='\n')
