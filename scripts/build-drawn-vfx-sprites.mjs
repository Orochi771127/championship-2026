// Hand-drawn move effect sprites -> code module (UNIQUE_PIXEL_MOVE_VFX_20261108).
//
// The drawings live in docs/art/production/move-vfx-drawn-r1/drawn-vfx.px.js and
// are made with the pxl pixel-art tool (MIT, a local authoring tool: it is not a
// game dependency). This script renders each sprite with pxl and writes its
// pixels back as the drawing's own one-character keys, so the game recolours the
// tone keys (o e m x c) with each move's palette and keeps the fixed keys.
//
// Usage: node scripts/build-drawn-vfx-sprites.mjs [--check]
//   PXL_HOME  the pxl checkout (default ~/.claude/skills/pxl-pixel-art)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'docs/art/production/move-vfx-drawn-r1/drawn-vfx.px.js';
const OUT = 'src/championship/presentation/vfx/drawnVfxSprites.js';
const TONES = 'oemxc';

export async function buildDrawnVfxSprites() {
  const home = process.env.PXL_HOME ?? path.join(os.homedir(), '.claude/skills/pxl-pixel-art');
  // A checkout runs pxl's TypeScript sources directly (Node >= 22.18 strips types); a package build has dist/.
  const entry = fs.existsSync(path.join(home, 'dist/index.js')) ? 'dist/index.js' : 'src/index.ts';
  const {loadProject} = await import(pathToFileURL(path.join(home, entry)).href);
  const source = fs.readFileSync(path.join(root, SOURCE), 'utf8');
  // The palette line maps every key to its preview colour; read it back to name each pixel.
  const pal = Object.fromEntries([...source.match(/pal\(\{([^}]*)\}\)/)[1].matchAll(/(\w):\s*"#([0-9a-fA-F]{6})"/g)].map(([, key, hex]) => [key, hex.toLowerCase()]));
  const keyOf = new Map(Object.entries(pal).map(([key, hex]) => [hex, key]));
  const names = [...source.matchAll(/sprite\("([^"_][^"]*)"/g)].map(m => m[1]);
  const project = loadProject(path.join(root, SOURCE));
  const sprites = {};
  for (const name of names) {
    const img = project.image(name), rows = [];
    for (let y = 0; y < img.h; y++) {
      let row = '';
      for (let x = 0; x < img.w; x++) {
        const v = img.data[y * img.w + x] >>> 0;
        if ((v & 255) < 128) { row += '.'; continue; }
        const hex = (v >>> 8).toString(16).padStart(6, '0');
        const key = keyOf.get(hex);
        if (!key) throw new Error(`DRAWN_VFX_UNKNOWN_COLOUR: ${name} ${x},${y} #${hex}`);
        row += key;
      }
      rows.push(row);
    }
    sprites[name] = {w: img.w, h: img.h, rows};
  }
  const fixed = Object.fromEntries(Object.entries(pal).filter(([key]) => !TONES.includes(key)).map(([key, hex]) => [key, parseInt(hex, 16)]));
  return {sprites, fixed};
}

export function serializeDrawnVfxSprites({sprites, fixed}) {
  const lines = Object.entries(sprites).map(([name, s]) => `  ${name}: sprite(${s.w}, ${s.h}, [\n${s.rows.map(r => `    ${JSON.stringify(r)}`).join(',\n')}\n  ])`);
  return `// Hand-drawn move effect sprites (UNIQUE_PIXEL_MOVE_VFX_20261108). GENERATED by
// scripts/build-drawn-vfx-sprites.mjs from ${SOURCE};
// edit the drawing, not this file. Keys: o outline, e edge, m main, x light,
// c highlight take the move's palette; the others keep DRAWN_VFX_FIXED colours.
const sprite = (w, h, rows) => Object.freeze({w, h, rows: Object.freeze(rows)});
export const DRAWN_VFX_FIXED = Object.freeze(${JSON.stringify(fixed)});
export const DRAWN_VFX_SPRITES = Object.freeze({
${lines.join(',\n')}
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = serializeDrawnVfxSprites(await buildDrawnVfxSprites());
  const target = path.join(root, OUT);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) { console.error('DRAWN_VFX_SPRITES_STALE: run node scripts/build-drawn-vfx-sprites.mjs'); process.exit(1); }
    console.log(`${OUT} is current`);
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote ${OUT}`);
  }
}
